import { FormEvent, ReactNode, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { get, send } from '../api';
import { ConfirmModal, Field } from '../components/ops';
import { ActingAsBar, LimitsGate } from '../components/limits';
import { Card, PageHeader } from '../components/ui';
import { label, money } from '../format';
import { useLoad } from '../hooks';
import type { Collateral, CollateralType, CurrencyInfo } from '../types';

interface Form {
  customerId: string; collateralRef: string; collateralType: string; description: string; currencyCode: string;
  haircut: string; maxLtv: string; prior: string;
}
const EMPTY: Form = { customerId: '', collateralRef: '', collateralType: '', description: '', currencyCode: 'INR', haircut: '', maxLtv: '', prior: '' };

export default function LimitsCollateralNew() {
  return (
    <>
      <PageHeader title="New collateral" sub="Registers the security in DRAFT. It counts for nothing until its valuation is approved, legal checks pass and it is activated." />
      <LimitsGate><FormBody /></LimitsGate>
    </>
  );
}

function FormBody() {
  const nav = useNavigate();
  const types = useLoad(() => get<CollateralType[]>('/limits/collateral-types'), []);
  const currencies = useLoad(() => get<CurrencyInfo[]>('/accounting/currencies'), []);
  const [f, setF] = useState<Form>(EMPTY);
  const [confirming, setConfirming] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const set = (k: keyof Form) => (e: { target: { value: string } }) => setF({ ...f, [k]: e.target.value });
  const type = (types.data ?? []).find(t => t.typeCode === f.collateralType);

  function body() {
    const b: Record<string, unknown> = {
      customerId: Number(f.customerId), collateralType: f.collateralType, description: f.description.trim(), currencyCode: f.currencyCode,
    };
    if (f.collateralRef.trim()) b.collateralRef = f.collateralRef.trim();
    if (f.haircut !== '') b.haircutPct = Number(f.haircut);
    if (f.maxLtv !== '') b.maxLtvPct = Number(f.maxLtv);
    if (f.prior !== '') b.priorChargeAmount = Number(f.prior);
    return b;
  }

  function check(e: FormEvent) {
    e.preventDefault();
    setError(null);
    if (!/^\d+$/.test(f.customerId.trim())) return setError('Customer id must be a whole number');
    if (!f.collateralType) return setError('Choose the collateral type');
    if (f.description.trim() === '') return setError('Describe the collateral (what it is, where, identifying numbers)');
    if (f.collateralRef.trim() && !/^[A-Za-z0-9_.:-]{1,64}$/.test(f.collateralRef.trim())) return setError('Reference may contain only letters, digits and . _ : - (up to 64)');
    if (f.haircut !== '' && !(Number(f.haircut) >= 0 && Number(f.haircut) <= 99.99)) return setError('Haircut must be between 0 and 99.99');
    if (f.maxLtv !== '' && !(Number(f.maxLtv) >= 0.01 && Number(f.maxLtv) <= 100)) return setError('Maximum LTV must be between 0.01 and 100');
    if (f.prior !== '' && !(Number(f.prior) >= 0)) return setError('Prior charge cannot be negative');
    setConfirming(true);
  }

  async function create() {
    const r = await send<Collateral>('POST', '/limits/collateral', body());
    nav(`/limits/collateral/${encodeURIComponent(r.collateralRef)}`);
  }

  const rows: [string, ReactNode][] = [
    ['Customer', f.customerId], ['Type', label(f.collateralType)], ['Description', f.description], ['Reference', f.collateralRef.trim() || 'Generated by the service'],
    ['Currency', f.currencyCode], ['Haircut', f.haircut !== '' ? `${f.haircut}%` : type ? `${type.defaultHaircutPct}% (type default)` : '-'],
    ['Maximum LTV', f.maxLtv !== '' ? `${f.maxLtv}%` : type ? `${type.maxLtvPct}% (type default)` : '-'],
  ];
  if (f.prior !== '') rows.push(['Prior charge', money(Number(f.prior))]);

  return (
    <>
      <ActingAsBar needed={false} />
      <Card title="Collateral details">
        <form onSubmit={check}>
          <div className="form-grid">
            <Field label="Customer id"><input inputMode="numeric" value={f.customerId} onChange={set('customerId')} /></Field>
            <Field label="Type" hint={type ? `Valuation valid ${type.valuationValidityDays} days${type.requiresCharge ? '; charge required' : ''}${type.requiresInsurance ? '; insurance required' : ''}` : undefined}>
              <select value={f.collateralType} onChange={set('collateralType')}>
                <option value="">Choose a type</option>
                {(types.data ?? []).map(t => <option key={t.typeCode} value={t.typeCode}>{t.typeCode} - {t.description}</option>)}
              </select>
            </Field>
            <Field label="Reference" hint="Optional"><input value={f.collateralRef} onChange={set('collateralRef')} placeholder="Generated if empty" /></Field>
            <Field label="Currency">
              <select value={f.currencyCode} onChange={set('currencyCode')}>
                {(currencies.data ?? []).filter(c => c.active).map(c => <option key={c.currencyCode} value={c.currencyCode}>{c.currencyCode} - {c.currencyName}</option>)}
                {!(currencies.data ?? []).some(c => c.currencyCode === 'INR') && <option value="INR">INR</option>}
              </select>
            </Field>
            <Field label="Haircut %" hint={type ? `Type default ${type.defaultHaircutPct}%` : 'Leave empty to use the type default'}><input type="number" step="0.01" min="0" max="99.99" value={f.haircut} onChange={set('haircut')} /></Field>
            <Field label="Maximum LTV %" hint={type ? `Type default ${type.maxLtvPct}%` : 'Leave empty to use the type default'}><input type="number" step="0.01" min="0.01" max="100" value={f.maxLtv} onChange={set('maxLtv')} /></Field>
            <Field label="Prior charge amount" hint="Amount another lender already has a claim for"><input type="number" step="0.01" min="0" value={f.prior} onChange={set('prior')} /></Field>
            <Field label="Description" wide><input value={f.description} onChange={set('description')} placeholder="e.g. Flat 402, Lake View Apartments, Pune; deed no. 1234/2021" /></Field>
          </div>
          {error && <div className="banner banner-bad" role="alert">{error}</div>}
          <button className="btn btn-primary">Review and register</button>
        </form>
      </Card>
      {confirming && <ConfirmModal title="Register this collateral?" rows={rows} confirmLabel="Register" note="It starts as DRAFT. Next: propose a valuation (a different person approves it), record the legal check, charge and insurance, then activate." onConfirm={create} onClose={() => setConfirming(false)} />}
    </>
  );
}
