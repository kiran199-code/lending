import { FormEvent, ReactNode, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { get, send } from '../api';
import { ConfirmModal, Field } from '../components/ops';
import { ActingAsBar, FACILITY_TYPES, LimitsGate } from '../components/limits';
import { Card, PageHeader } from '../components/ui';
import { label, money } from '../format';
import { useLoad } from '../hooks';
import type { BranchInfo, CurrencyInfo, Facility } from '../types';

interface Form {
  customerId: string; facilityRef: string; facilityType: string; parentRef: string; productCode: string; currencyCode: string;
  branchCode: string; revolving: boolean; dpGoverned: boolean; amount: string; maxSingle: string; effectiveFrom: string;
  expiry: string; sanctionRefId: string;
}
const EMPTY: Form = {
  customerId: '', facilityRef: '', facilityType: 'PRODUCT', parentRef: '', productCode: '', currencyCode: 'INR', branchCode: '',
  revolving: false, dpGoverned: false, amount: '', maxSingle: '', effectiveFrom: '', expiry: '', sanctionRefId: '',
};

export default function LimitsFacilityNew() {
  return (
    <>
      <PageHeader title="New facility" sub="Creates the limit in DRAFT. It cannot be drawn on until a second person approves its activation." />
      <LimitsGate><FormBody /></LimitsGate>
    </>
  );
}

function FormBody() {
  const nav = useNavigate();
  const currencies = useLoad(() => get<CurrencyInfo[]>('/accounting/currencies'), []);
  const branches = useLoad(() => get<BranchInfo[]>('/accounting/branches'), []);
  const [f, setF] = useState<Form>(EMPTY);
  const [confirming, setConfirming] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const cid = f.customerId.trim();
  const parents = useLoad(
    () => (/^\d+$/.test(cid) && f.facilityType !== 'OVERALL' ? get<Facility[]>('/limits/facilities', { customerId: cid }) : Promise.resolve([] as Facility[])),
    [cid, f.facilityType],
  );
  const set = (k: keyof Form) => (e: { target: { value: string } }) => setF({ ...f, [k]: e.target.value });
  const parent = (parents.data ?? []).find(p => p.facilityRef === f.parentRef);

  function body() {
    const b: Record<string, unknown> = {
      customerId: Number(cid), facilityType: f.facilityType, currencyCode: f.currencyCode, sanctionedAmount: Number(f.amount),
      revolving: f.revolving, dpGoverned: f.dpGoverned,
    };
    if (f.facilityRef.trim()) b.facilityRef = f.facilityRef.trim();
    if (f.facilityType !== 'OVERALL' && f.parentRef) b.parentRef = f.parentRef;
    if (f.productCode.trim()) b.productCode = f.productCode.trim().toUpperCase();
    if (f.branchCode) b.branchCode = f.branchCode;
    if (f.maxSingle !== '') b.maxSingleAmount = Number(f.maxSingle);
    if (f.effectiveFrom) b.effectiveFrom = f.effectiveFrom;
    if (f.expiry) b.expiryDate = f.expiry;
    if (f.sanctionRefId.trim()) b.sanctionRefId = Number(f.sanctionRefId);
    return b;
  }

  function check(e: FormEvent) {
    e.preventDefault();
    setError(null);
    if (!/^\d+$/.test(cid)) return setError('Customer id must be a whole number');
    if (f.facilityRef.trim() && !/^[A-Za-z0-9_.:-]{1,64}$/.test(f.facilityRef.trim())) return setError('Reference may contain only letters, digits and . _ : - (up to 64)');
    if (f.facilityType !== 'OVERALL' && !f.parentRef) return setError('A sub-limit or product limit needs a parent facility; create the overall limit first');
    if (f.facilityType === 'OVERALL' && !f.expiry) return setError('An overall limit needs an expiry date');
    if (f.amount === '' || !(Number(f.amount) >= 0)) return setError('Sanctioned amount must be zero or more');
    if (f.maxSingle !== '' && !(Number(f.maxSingle) > 0)) return setError('Largest single drawdown must be greater than zero');
    if (f.sanctionRefId.trim() && !/^\d+$/.test(f.sanctionRefId.trim())) return setError('Sanction reference must be a whole number');
    if (parent && Number(f.amount) > parent.sanctionedAmount) return setError(`The parent's limit is ${money(parent.sanctionedAmount)}; this limit cannot be larger`);
    setConfirming(true);
  }

  async function create() {
    const r = await send<Facility>('POST', '/limits/facilities', body());
    nav(`/limits/facilities/${encodeURIComponent(r.facilityRef)}`);
  }

  const rows: [string, ReactNode][] = [
    ['Customer', cid], ['Type', label(f.facilityType)], ['Reference', f.facilityRef.trim() || 'Generated by the service'],
    ['Parent', f.facilityType === 'OVERALL' ? 'None' : f.parentRef],
    ['Sanctioned', `${money(Number(f.amount))} ${f.currencyCode}`],
  ];
  if (f.productCode.trim()) rows.push(['Product', f.productCode.trim().toUpperCase()]);
  if (f.expiry) rows.push(['Expires', f.expiry]);
  rows.push(['Revolving', f.revolving ? 'Yes' : 'No'], ['Governed by drawing power', f.dpGoverned ? 'Yes' : 'No']);

  return (
    <>
      <ActingAsBar />
      <Card title="Facility details">
        <form onSubmit={check}>
          <div className="form-grid">
            <Field label="Customer id"><input inputMode="numeric" value={f.customerId} onChange={set('customerId')} /></Field>
            <Field label="Type">
              <select value={f.facilityType} onChange={e => setF({ ...f, facilityType: e.target.value, parentRef: '' })}>
                {FACILITY_TYPES.map(([k, v]) => <option key={k} value={k}>{v}</option>)}
              </select>
            </Field>
            {f.facilityType !== 'OVERALL' && (
              <Field label="Parent facility" hint={!/^\d+$/.test(cid) ? 'Enter the customer id to list their facilities' : (parents.data ?? []).length === 0 && !parents.loading ? 'This customer has no facility yet' : undefined}>
                <select value={f.parentRef} onChange={set('parentRef')}>
                  <option value="">Choose a parent</option>
                  {(parents.data ?? []).filter(p => p.status !== 'CLOSED').map(p => (
                    <option key={p.facilityRef} value={p.facilityRef}>{p.facilityRef} - {label(p.facilityType)} - {money(p.sanctionedAmount)} ({label(p.status)})</option>
                  ))}
                </select>
              </Field>
            )}
            <Field label="Reference" hint="Optional. SANC-<sanction reference> links the facility to loans created from that sanction by the bulk script">
              <input value={f.facilityRef} onChange={set('facilityRef')} placeholder="Generated if empty" />
            </Field>
            <Field label="Product code" hint="For a product limit: the product its loans use"><input value={f.productCode} onChange={set('productCode')} /></Field>
            <Field label="Currency">
              <select value={f.currencyCode} onChange={set('currencyCode')}>
                {(currencies.data ?? []).filter(c => c.active).map(c => <option key={c.currencyCode} value={c.currencyCode}>{c.currencyCode} - {c.currencyName}</option>)}
                {!(currencies.data ?? []).some(c => c.currencyCode === 'INR') && <option value="INR">INR</option>}
              </select>
            </Field>
            <Field label="Branch">
              <select value={f.branchCode} onChange={set('branchCode')}>
                <option value="">Not specified</option>
                {(branches.data ?? []).filter(b => b.active).map(b => <option key={b.branchCode} value={b.branchCode}>{b.branchCode} - {b.branchName}</option>)}
              </select>
            </Field>
            <Field label="Sanctioned amount" hint={parent ? `Parent limit ${money(parent.sanctionedAmount)}` : undefined}>
              <input type="number" step="0.01" min="0" value={f.amount} onChange={set('amount')} />
            </Field>
            <Field label="Largest single drawdown" hint="Optional cap on one loan"><input type="number" step="0.01" min="0" value={f.maxSingle} onChange={set('maxSingle')} /></Field>
            <Field label="Effective from"><input type="date" value={f.effectiveFrom} onChange={set('effectiveFrom')} /></Field>
            <Field label="Expiry date" hint={f.facilityType === 'OVERALL' ? 'Required for an overall limit' : 'Cannot be after the parent expires'}>
              <input type="date" value={f.expiry} onChange={set('expiry')} />
            </Field>
            <Field label="Sanction reference" hint="Optional, whole number"><input inputMode="numeric" value={f.sanctionRefId} onChange={set('sanctionRefId')} /></Field>
          </div>
          <p>
            <label><input type="checkbox" checked={f.revolving} onChange={e => setF({ ...f, revolving: e.target.checked })} /> Revolving: repayments make the limit available again</label>
            <br />
            <label><input type="checkbox" checked={f.dpGoverned} onChange={e => setF({ ...f, dpGoverned: e.target.checked })} /> Governed by drawing power: availability is capped by the lendable value of the allocated collateral</label>
          </p>
          {error && <div className="banner banner-bad" role="alert">{error}</div>}
          <button className="btn btn-primary">Review and create</button>
        </form>
      </Card>
      {confirming && (
        <ConfirmModal title="Create this facility?" rows={rows} confirmLabel="Create facility"
          note="It starts as DRAFT. Propose its activation from the facility page; a different person must approve it."
          onConfirm={create} onClose={() => setConfirming(false)} />
      )}
    </>
  );
}
